#!/usr/bin/env node
// Breadcrumb trail ant: node ants/gen-crumb.ts [--no-food-trail] > ants/crumb.asm
//
// Alternative to the mod-3 gradient of ants/gen-trail.ts, which loops (see docs/TRAILS.md).
//   * Heading: the ant's direction is tracked in its pc (six copies of every routine), because Classic has no way
//     to read it. Only `turn` changes it, and every `turn` is followed by a jump into the matching copy.
//   * Breadcrumbs: when an explorer enters an uncoded cell it writes the direction BACK to the cell it came from, as the
//     3-bit value (dir + 1) on markers 0..2 (0 = uncoded). A cell is written once and never changed, so a cell's parent is
//     always older than the cell: following parents ends at the nest and can never loop.
//   * Return: a carrier reads the 3 bits under it, turns to that direction (at most 3 turns) and moves. It never needs vision.
//     If the move is blocked it retries, and 1 time in 4 sidesteps first (a jam of carriers and explorers can otherwise freeze).
//   * Food trail (marker 3, optional): carriers mark every cell they walk. An empty ant that is on, or sees, a food-trail
//     cell whose parent pointer points back at it follows it outwards. A trail end is eaten (1 in 4) so stale trails vanish.
//     A follower whose trail move is blocked steps off the lane (random side): a carrier coming the other way would
//     otherwise wait for it forever (head-on deadlock on a one-cell-wide trail).
//   * Food that lies on a nest cell is a delivered packet and is never picked up.
const foodTrail = !process.argv.includes('--no-food-trail');
const Lh = (h: number): number => (h + 5) % 6, Rh = (h: number): number => (h + 1) % 6, Bh = (h: number): number => (h + 3) % 6;
const val = (parentDir: number): number => parentDir + 1; // 1..6, 0 = uncoded
const out: string[] = [];
const L = (label: string, text: string): void => { out.push(`${label}: ${text}`); };
const I = (text: string): void => { out.push(`  ${text}`); };
const C = (text: string): void => { out.push(`; ${text}`); };

/** Instructions that turn from heading h to heading `to` (shortest way, ties turn right). */
const rot = (h: number, to: number): string[] => {
  const d = (to - h + 6) % 6;
  return Array.from({ length: d <= 3 ? d : 6 - d }, () => (d <= 3 ? 'turn right' : 'turn left'));
};
/** Read the 3 marker bits of `rel`; label `pre` is the entry, leaf(v) names the label to continue at for value v. */
const tree = (rel: string, pre: string, leaf: (v: number) => string): void => {
  const node = (k: number, acc: number): string => (k === 0 ? pre : `${pre}_${k}_${acc}`);
  const emit = (k: number, acc: number): void => {
    if (k === 3) { L(node(3, acc), `goto ${leaf(acc)}`); return; }
    L(node(k, acc), `sense ${rel} marker ${k} else ${node(k + 1, acc)}`);
    I(`goto ${node(k + 1, acc | (1 << k))}`);
    emit(k + 1, acc); emit(k + 1, acc | (1 << k));
  };
  emit(0, 0);
};
/** Test whether `rel` holds exactly the 3-bit value v: continue at ok if so, at fail otherwise. `pre` keeps labels unique. */
const equals = (rel: string, v: number, pre: string, ok: string, fail: string): void => {
  let pending: string | null = null;
  const add = (text: string): void => { out.push(pending ? `${pending}: ${text}` : `  ${text}`); pending = null; };
  for (let k = 0; k < 3; k++) {
    if ((v >> k) & 1) add(`sense ${rel} marker ${k} else ${fail}`);
    else { add(`sense ${rel} marker ${k} else ${pre}_${k}`); add(`goto ${fail}`); pending = `${pre}_${k}`; }
  }
  add(`goto ${ok}`);
};

C(`breadcrumb ant (${foodTrail ? 'parent pointers + food trail' : 'parent pointers only'}); generated by ants/gen-crumb.ts, do not edit`);
C('the ant starts with direction 0, which is heading 0');
for (let h = 0; h < 6; h++) {
  C(`---- heading ${h} ----`);
  C('start of a trip: uniform random heading, then arrive on the nest cell');
  L(`st${h}`, `flipzero 6 else st${h}_1`); I(`goto a${h}`);
  L(`st${h}_1`, `flipzero 5 else st${h}_2`); I('turn left'); I(`goto a${Lh(h)}`);
  L(`st${h}_2`, `flipzero 4 else st${h}_3`); I('turn left'); I('turn left'); I(`goto a${Lh(Lh(h))}`);
  L(`st${h}_3`, `flipzero 3 else st${h}_4`); for (let i = 0; i < 3; i++) I('turn left'); I(`goto a${Bh(h)}`);
  L(`st${h}_4`, `flipzero 2 else st${h}_5`); I('turn right'); I('turn right'); I(`goto a${Rh(Rh(h))}`);
  L(`st${h}_5`, 'turn right'); I(`goto a${Rh(h)}`);

  C('explorer arrival: if the cell is uncoded, write the direction back to where we came from');
  tree('here', `a${h}`, (v) => (v === 0 ? `aw${h}` : `x${h}`));
  { const on = [0, 1, 2].filter((k) => (val(Bh(h)) >> k) & 1); L(`aw${h}`, `mark ${on[0]}`); on.slice(1).forEach((k) => I(`mark ${k}`)); I(`goto x${h}`); }

  C('explorer decision: food here, food ahead/left/right (never on the nest), food trail, wander');
  L(`x${h}`, `sense here food else x${h}a`); I(`sense here home else x${h}pk`); I(`goto x${h}a`);
  L(`x${h}pk`, `pickup else x${h}a`); if (foodTrail) I('mark 3'); I(`goto r${h}`);
  L(`x${h}a`, `sense ahead food else x${h}b`); I(`sense ahead home else m${h}`); I(`goto x${h}b`);
  L(`x${h}b`, `sense leftahead food else x${h}c`); I(`sense leftahead home else x${h}bl`); I(`goto x${h}c`);
  L(`x${h}bl`, 'turn left'); I(`goto m${Lh(h)}`);
  L(`x${h}c`, `sense rightahead food else x${h}t`); I(`sense rightahead home else x${h}cr`); I(`goto x${h}t`);
  L(`x${h}cr`, 'turn right'); I(`goto m${Rh(h)}`);
  if (foodTrail) {
    L(`x${h}t`, `sense here marker 3 else x${h}j`);
    I(`sense ahead marker 3 else x${h}tl`); equals('ahead', val(Bh(h)), `x${h}te`, `mt${h}`, `x${h}tl`);
    L(`x${h}tl`, `sense leftahead marker 3 else x${h}tr`); equals('leftahead', val(Bh(Lh(h))), `x${h}le`, `x${h}tlt`, `x${h}tr`);
    L(`x${h}tr`, `sense rightahead marker 3 else x${h}end`); equals('rightahead', val(Bh(Rh(h))), `x${h}re`, `x${h}trt`, `x${h}end`);
    L(`x${h}end`, `flipzero 4 else x${h}w`); I('unmark 3'); I(`goto x${h}w`);
    L(`x${h}j`, `sense ahead marker 3 else x${h}w`); equals('ahead', val(Bh(h)), `x${h}je`, `mt${h}`, `x${h}w`);
    L(`x${h}tlt`, 'turn left'); I(`goto mt${Lh(h)}`);
    L(`x${h}trt`, 'turn right'); I(`goto mt${Rh(h)}`);
    L(`mt${h}`, `move else x${h}y`); I(`goto a${h}`);
    L(`x${h}y`, `flipzero 2 else x${h}yr`); I('turn left'); I(`goto m${Lh(h)}`);
    L(`x${h}yr`, 'turn right'); I(`goto m${Rh(h)}`);
  } else {
    L(`x${h}t`, `goto x${h}w`);
  }
  L(`x${h}w`, `flipzero 5 else m${h}`);                  // falls through 1 time in 5 (turn), else straight on
  I(`flipzero 2 else x${h}wr`); I('turn left'); I(`goto m${Lh(h)}`);
  L(`x${h}wr`, 'turn right'); I(`goto m${Rh(h)}`);
  L(`m${h}`, `move else x${h}rot`); I(`goto a${h}`);
  L(`x${h}rot`, `flipzero 2 else x${h}rr`); I('turn left'); I(`goto x${Lh(h)}`);
  L(`x${h}rr`, 'turn right'); I(`goto x${Rh(h)}`);

  C('carrier: drop on the nest, step into the nest if it is ahead, else follow the parent pointer');
  L(`r${h}`, `sense here home else r${h}a`); I(`goto rd${h}`);
  L(`r${h}a`, `sense ahead home else rc${h}`); I(`goto rh${h}`);
  L(`rh${h}`, `move else r${h}`); I(`goto rd${h}`);
  L(`rd${h}`, 'drop'); I(`goto st${h}`);
  tree('here', `rc${h}`, (v) => (v === 0 || v === 7 ? `lost${h}` : `ro${h}_${v}`));
  for (let v = 1; v <= 6; v++) {
    const lines = [...rot(h, v - 1), `goto mv${v - 1}`];
    out.push(`ro${h}_${v}: ${lines[0]}`, ...lines.slice(1).map((t) => `  ${t}`));
  }
  L(`mv${h}`, `move else mb${h}`); if (foodTrail) I('mark 3'); I(`goto r${h}`);
  L(`mb${h}`, `flipzero 4 else r${h}`); I(`goto lost${h}`); // blocked: now and then sidestep, which breaks jams
  C('carrier on a cell with no usable code: random step, then look again');
  L(`lost${h}`, `flipzero 2 else lost${h}r`); I('turn left'); I(`goto lm${Lh(h)}`);
  L(`lost${h}r`, 'turn right'); I(`goto lm${Rh(h)}`);
  L(`lm${h}`, `move else lost${h}`); I(`goto r${h}`);
}
process.stdout.write(`${out.join('\n')}\n`);
