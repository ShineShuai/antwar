#!/usr/bin/env node
// Writes a hand-designed trail ant in flat assembly: node ants/gen-trail.ts [--no-food-trail] > ants/trail.asm
//
// This is the "trail kit" of reference.html (Easy authoring tab) built by hand, to measure whether it works:
//   * Gradient: an outbound ant carries phase p = (steps from the nest) mod 3 in its pc (three copies of every
//     routine). On each new cell it reads the cell's code: a coded cell is adopted (the ant joins that trail's
//     numbering), an uncoded cell gets marker p (first writer wins, so codes never change).
//     Code k is the one-hot marker k (markers 0..2).
//   * Return: a carrier steps to a neighbour whose code is p-1, drops when it stands on the nest.
//   * Food trail (marker 3, optional): carriers mark every cell they walk; empty ants that stand on or see a food-trail cell
//     with code p+1 follow it outwards; an ant at a trail end eats the marker (1 in 4) so stale trails vanish.
//   * Nest food is never picked up (food on a Home cell is a delivered packet).
//   * Anti-jam (same two rules as ants/gen-crumb.ts): a follower whose trail move is blocked steps off the lane; a blocked
//     carrier sidesteps one time in four.
// An ant is never told where it is: every routine re-reads the cell it stands on, so a wrong guess costs a few rounds.
const foodTrail = !process.argv.includes('--no-food-trail');
const nx = (p: number): number => (p + 1) % 3, pv = (p: number): number => (p + 2) % 3;
const out: string[] = [];
const L = (label: string, text: string): void => { out.push(`${label}: ${text}`); };
const I = (text: string): void => { out.push(`  ${text}`); };
const C = (text: string): void => { out.push(`; ${text}`); };
const turns = (k: number): void => { for (let i = 0; i < k; i++) I('turn left'); };

C(`trail ant (${foodTrail ? 'gradient + food trail' : 'gradient only'}); generated by ants/gen-trail.ts, do not edit by hand`);
C('start of a trip: uniform random heading (0..5 turns), then arrive on the nest cell');
L('start', 'flipzero 6 else s1'); I('goto a0');
L('s1', 'flipzero 5 else s2'); turns(1); I('goto a0');
L('s2', 'flipzero 4 else s3'); turns(2); I('goto a0');
L('s3', 'flipzero 3 else s4'); turns(3); I('goto a0');
L('s4', 'flipzero 2 else s5'); I('turn right'); I('turn right'); I('goto a0');
L('s5', 'turn right'); I('goto a0');

C('delivery: shared by all phases');
L('rd', 'drop'); I('goto start');

C('carrier lost (no code under it): walk randomly until a coded cell is found');
L('lost', 'sense here home else lw'); I('goto rd');
L('lw', 'flipzero 3 else lw1'); I('turn left'); I('goto lm');
L('lw1', 'flipzero 2 else lm'); I('turn right');
L('lm', 'move else lw'); I('goto ls0');
for (let k = 0; k < 3; k++) { L(`ls${k}`, `sense here marker ${k} else ${k < 2 ? `ls${k + 1}` : 'lost'}`); I(`goto r${k}`); }

for (let p = 0; p < 3; p++) {
  C(`---- phase ${p} ----`);
  C('explorer arrival: sync with the code under us, or write ours');
  L(`a${p}`, `sense here marker ${p} else a${p}b`); I(`goto x${p}`);
  L(`a${p}b`, `sense here marker ${nx(p)} else a${p}c`); I(`goto x${nx(p)}`);
  L(`a${p}c`, `sense here marker ${pv(p)} else a${p}d`); I(`goto x${pv(p)}`);
  L(`a${p}d`, `mark ${p}`); I(`goto x${p}`);

  C('explorer decision: food here, food ahead/left/right (never on the nest), food trail, wander');
  L(`x${p}`, `sense here food else x${p}a`);
  I(`sense here home else x${p}pk`); I(`goto x${p}a`);
  L(`x${p}pk`, `pickup else x${p}a`); if (foodTrail) I('mark 3'); turns(3); I(`goto r${p}`); // about-face: the way back is behind us
  L(`x${p}a`, `sense ahead food else x${p}b`); I(`sense ahead home else m${p}`); I(`goto x${p}b`);
  L(`x${p}b`, `sense leftahead food else x${p}c`); I(`sense leftahead home else x${p}bl`); I(`goto x${p}c`);
  L(`x${p}bl`, 'turn left'); I(`goto m${p}`);
  L(`x${p}c`, `sense rightahead food else x${p}t`); I(`sense rightahead home else x${p}cr`); I(`goto x${p}t`);
  L(`x${p}cr`, 'turn right'); I(`goto m${p}`);
  if (foodTrail) {
    L(`x${p}t`, `sense here marker 3 else x${p}j`);
    I(`sense ahead marker 3 else x${p}tl`); I(`sense ahead marker ${nx(p)} else x${p}tl`); I(`goto mt${p}`);
    L(`x${p}tl`, `sense leftahead marker 3 else x${p}tr`); I(`sense leftahead marker ${nx(p)} else x${p}tr`); I('turn left'); I(`goto mt${p}`);
    L(`x${p}tr`, `sense rightahead marker 3 else x${p}end`); I(`sense rightahead marker ${nx(p)} else x${p}end`); I('turn right'); I(`goto mt${p}`);
    L(`x${p}end`, `flipzero 4 else x${p}w`); I('unmark 3'); I(`goto x${p}w`);
    L(`x${p}j`, `sense ahead marker 3 else x${p}w`); I(`sense ahead marker ${nx(p)} else x${p}w`); I(`goto mt${p}`);
  } else {
    L(`x${p}t`, `goto x${p}w`);
  }
  L(`x${p}w`, `flipzero 5 else m${p}`);                  // falls through 1 time in 5 (turn), else straight on
  I(`flipzero 2 else x${p}wr`); I('turn left'); I(`goto m${p}`);
  L(`x${p}wr`, 'turn right'); I(`goto m${p}`);
  L(`m${p}`, `move else x${p}rot`); I(`goto a${nx(p)}`);
  L(`mt${p}`, `move else x${p}y`); I(`goto a${nx(p)}`);   // trail move: when blocked, step off the lane
  L(`x${p}y`, `flipzero 2 else x${p}yr`); I('turn left'); I(`goto m${p}`);
  L(`x${p}yr`, 'turn right'); I(`goto m${p}`);
  L(`x${p}rot`, `flipzero 2 else x${p}rr`); I('turn left'); I(`goto x${p}`);
  L(`x${p}rr`, 'turn right'); I(`goto x${p}`);

  C('carrier at a cell with code p: drop if on the nest, enter the nest if it is ahead, else follow code p-1');
  L(`r${p}`, `sense here home else r${p}a`); I('goto rd');
  L(`r${p}a`, `sense ahead home else r${p}g`); I(`goto rh${p}`);
  L(`rh${p}`, `move else r${p}`); I('goto rd');
  L(`r${p}g`, `sense ahead marker ${pv(p)} else r${p}gl`); I(`goto rm${p}`);
  L(`r${p}gl`, `sense leftahead marker ${pv(p)} else r${p}gr`);
  I(`sense rightahead marker ${pv(p)} else r${p}tl`); I(`flipzero 2 else r${p}trr`);
  L(`r${p}tl`, 'turn left'); I(`goto rm${p}`);
  L(`r${p}trr`, 'turn right'); I(`goto rm${p}`);
  L(`r${p}gr`, `sense rightahead marker ${pv(p)} else r${p}hl`); I('turn right'); I(`goto rm${p}`);
  L(`r${p}hl`, `sense leftahead home else r${p}hr`); I('turn left'); I(`goto rh${p}`);
  L(`r${p}hr`, 'sense rightahead home else lost'); I('turn right'); I(`goto rh${p}`);
  L(`rm${p}`, `move else mb${p}`); I(`goto ra${pv(p)}`);
  L(`mb${p}`, `flipzero 4 else r${p}`); I('goto lost');   // blocked: now and then sidestep, which breaks jams

  C('carrier arrival: mark the way, then sync with the code under us');
  L(`ra${p}`, foodTrail ? 'mark 3' : `sense here marker ${p} else ra${p}b`);
  if (foodTrail) I(`sense here marker ${p} else ra${p}b`);
  I(`goto r${p}`);
  L(`ra${p}b`, `sense here marker ${nx(p)} else ra${p}c`); I(`goto r${nx(p)}`);
  L(`ra${p}c`, `sense here marker ${pv(p)} else lost`); I(`goto r${pv(p)}`);
}
process.stdout.write(`${out.join('\n')}\n`);
